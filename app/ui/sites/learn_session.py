"""The learning page: show the front, reveal the solution, rate yourself.

The look comes from learning_site.py (generated by Qt Designer, do not edit it
by hand). Only the logic behind it lives here.

Buttons:
- show solution:   show the back at the bottom (pressing again -> nothing happens)
- unknown / known but difficult / easily known:  rating. These buttons only appear
                   once the solution is shown and disappear again with the next card
- delete:          delete the current card from the deck (no confirmation)
- edit:            open the current card in the card editor
"""
from datetime import datetime

from PySide6.QtCore import Qt, QTimer, Signal, Slot
from PySide6.QtGui import QFont, QPainter
from PySide6.QtWidgets import QGraphicsTextItem, QPushButton, QSizePolicy, QVBoxLayout, QWidget

from app.logic import leitner
from app.models.deck import Deck
from app.models.flashcard import Card, Page
from app.models.learnblock import LearnBlock
from app.storage.repository import DeckRepository, LearnBlockRepository
from app.ui.canvas.page_scene import PageScene
from app.ui.sites.learning_site import Ui_card_learner

WAIT_CHECK_MS = 10_000   # if no card is due right now: check every 10 s


class LearnSession(QWidget):
    back_signal = Signal()                # back to the learn block overview
    edit_card_signal = Signal(object, object)   # (deck, card) -> open in the card editor

    def __init__(self, deck_repository: DeckRepository, block_repository: LearnBlockRepository, parent=None):
        super().__init__(parent)
        self.deck_repository = deck_repository
        self.block_repository = block_repository

        self.block: LearnBlock | None = None
        self.deck: Deck | None = None
        self.card: Card | None = None
        self.solution_shown = False
        self.upper_scene = None   # keep references, otherwise Python garbage-collects the scenes
        self.lower_scene = None

        """UI from the Designer template"""
        self.ui = Ui_card_learner()
        self.ui.setupUi(self)
        # In the template the layout is attached to a widget with a fixed size.
        # This makes it grow with the window:
        outer = QVBoxLayout(self)
        outer.setContentsMargins(0, 0, 0, 0)
        outer.addWidget(self.ui.verticalLayoutWidget)

        self.ui.deck_title.setFont(QFont("Comic Sans MS", 20))
        self.upper_view = self.ui.upper_card_scene   # front
        self.lower_view = self.ui.graphicsView       # back
        for view in (self.upper_view, self.lower_view):
            view.setRenderHint(QPainter.RenderHint.Antialiasing)
            view.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
            view.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
            view.setVerticalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)

        # "zurück" is missing in the template -> added at the top left (can be moved into the Designer file)
        self.back_button = QPushButton("zurück")
        self.back_button.setFont(QFont("Comic Sans MS", 15))
        self.ui.left_layout.addWidget(self.back_button)
        self.ui.left_layout.addStretch()

        # rating buttons: when hidden they keep their space so the back side does not jump
        self.rating_buttons = [self.ui.unknown, self.ui.partially_known_button, self.ui.easily_known_button]
        for button in self.rating_buttons:
            policy = button.sizePolicy()
            policy.setRetainSizeWhenHidden(True)
            button.setSizePolicy(policy)
        self._set_rating_visible(False)

        self.wait_timer = QTimer(self)
        self.wait_timer.setInterval(WAIT_CHECK_MS)
        self.wait_timer.timeout.connect(self.show_next_card)

        """Button connections"""
        self.ui.next_card_button.clicked.connect(self.show_solution)
        self.ui.unknown.clicked.connect(lambda: self.rate(leitner.UNKNOWN))
        self.ui.partially_known_button.clicked.connect(lambda: self.rate(leitner.PARTIAL))
        self.ui.easily_known_button.clicked.connect(lambda: self.rate(leitner.KNOWN))
        self.ui.delete_button.clicked.connect(self.delete_card)
        self.back_button.clicked.connect(self.leave)
        self.ui.edit_button.clicked.connect(self.edit_card)

    # ------------------------------------------------------------------ Flow
    def start(self, block: LearnBlock, deck: Deck):
        """Starts learning a learn block"""
        self.block = block
        self.deck = deck
        self.ui.deck_title.setText(deck.name)
        self.show_next_card()

    @Slot()
    def show_next_card(self):
        self.wait_timer.stop()
        self.solution_shown = False
        self._set_rating_visible(False)   # new card -> rating only after revealing
        self.card = leitner.next_card(self.block, self.deck, datetime.now())
        if self.card is None:
            self._show_nothing_due()
            self.wait_timer.start()   # as soon as a card becomes due, it appears by itself
            return
        self._set_scenes(self._card_scene(self.card.front), self._card_scene(Page()))  # back still empty

    @Slot()
    def show_solution(self):
        if self.card is None or self.solution_shown:
            return   # no card or already revealed -> nothing happens
        self.solution_shown = True
        self._set_scenes(self.upper_scene, self._card_scene(self.card.back))
        self._set_rating_visible(True)

    def rate(self, rating: str):
        if self.card is None or not self.solution_shown:
            return   # reveal first, then rate
        leitner.rate(self.block.progress_for(self.card.id), rating, datetime.now())
        self.block_repository.save(self.block)
        self.show_next_card()

    @Slot()
    def delete_card(self):
        if self.card is None:
            return
        self.deck_repository.delete_card(self.deck, self.card)
        self.block.progress.pop(self.card.id, None)
        self.block_repository.save(self.block)
        self.show_next_card()

    @Slot()
    def edit_card(self):
        if self.card is None:
            return   # no card right now -> nothing happens
        self.edit_card_signal.emit(self.deck, self.card)

    def refresh_card(self):
        """Redisplay the current card after editing it in the editor.
        If the card has been deleted in the meantime, the next one comes up."""
        if self.card is None or self.deck is None:
            return
        current = self.deck.find_card(self.card.id)
        if current is None:
            self.show_next_card()
            return
        self.card = current
        back = self._card_scene(current.back) if self.solution_shown else self._card_scene(Page())
        self._set_scenes(self._card_scene(current.front), back)

    @Slot()
    def leave(self):
        self.wait_timer.stop()
        self.back_signal.emit()

    # ------------------------------------------------------------------ Display
    def _set_rating_visible(self, visible: bool):
        for button in self.rating_buttons:
            button.setVisible(visible)

    def _card_scene(self, page: Page) -> PageScene:
        """The same scene as in the editor, but view-only"""
        return PageScene(page, self.deck_repository.images_dir(self.deck), read_only=True)

    def _show_nothing_due(self):
        now = datetime.now()
        if not self.deck.cards:
            text = "Dieses Deck hat noch keine Karten."
        elif leitner.is_finished_today(self.block, self.deck, now):
            text = "Für heute ist alles gelernt!"
        else:
            next_time = leitner.next_due_time(self.block, self.deck)
            text = "Gerade ist keine Karte dran."
            if next_time is not None:
                text += f"\nNächste Karte um {next_time:%H:%M} Uhr."
        scene = self._card_scene(Page())
        message = QGraphicsTextItem(text)
        message.setFont(QFont("Comic Sans MS", 28))
        message.setTextWidth(scene.width() - 100)
        option = message.document().defaultTextOption()
        option.setAlignment(Qt.AlignmentFlag.AlignCenter)   # centered text
        message.document().setDefaultTextOption(option)
        rect = message.boundingRect()
        message.setPos((scene.width() - rect.width()) / 2, (scene.height() - rect.height()) / 2)
        scene.addItem(message)
        self._set_scenes(scene, self._card_scene(Page()))

    def _set_scenes(self, upper: PageScene, lower: PageScene):
        self.upper_scene, self.lower_scene = upper, lower
        self.upper_view.setScene(upper)
        self.lower_view.setScene(lower)
        self._fit_views()

    def _fit_views(self):
        """Always show the whole card as large as possible"""
        for view in (self.upper_view, self.lower_view):
            if view.scene() is not None:
                view.fitInView(view.scene().sceneRect(), Qt.AspectRatioMode.KeepAspectRatio)

    def resizeEvent(self, event):
        super().resizeEvent(event)
        self._fit_views()

    def showEvent(self, event):
        super().showEvent(event)
        QTimer.singleShot(0, self._fit_views)   # sizes are only known after the page is shown
